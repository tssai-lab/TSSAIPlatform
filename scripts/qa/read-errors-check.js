// 用 Playwright CLI run-code --filename 执行；依赖本地隔离夹具，不连接真实后端。
async (page) => {
  await page.evaluate(() => localStorage.removeItem('taskMetricsChartStyle'));
  await page.reload();
  const checked = [];
  const assert = (ok, name) => { if (!ok) throw new Error(name); checked.push(name); };
  const mode = values => page.evaluate(values => Object.assign(window.__qa, values), values);
  const metrics = page.locator('#metrics');
  const codes = page.locator('#code-list');
  const refresh = () => metrics.getByRole('button', { name: 'reload 刷新', exact: true }).click();
  const query = () => codes.getByRole('button', { name: '查 询', exact: true }).click();
  await metrics.getByRole('switch').click();
  assert(!(await metrics.getByRole('switch').isChecked()), '关闭自动刷新');
  await metrics.getByText('1', { exact: true }).waitFor();
  assert(await codes.getByRole('cell', { name: '代码 B', exact: true }).isVisible(), '正常查询显示两份代码');

  const updated = await metrics.getByText(/^更新于/).textContent();
  await mode({ metrics: 'error' });
  await refresh();
  await metrics.getByText('训练指标加载失败', { exact: true }).waitFor();
  assert(await metrics.getByText('1', { exact: true }).isVisible(), '刷新失败保留旧指标');
  assert(await metrics.getByText(/^更新于/).textContent() === updated, '失败不更新成功时间');
  assert(await metrics.getByText(/当前保留上一次成功查询/).isVisible(), '旧数据明确标记未更新');
  await page.screenshot({ path: 'output/playwright/metrics-stale.png', fullPage: true });

  await page.getByRole('button', { name: '测试切换 B', exact: true }).click();
  await metrics.getByText('训练指标加载失败', { exact: true }).waitFor();
  assert(await metrics.locator('canvas').count() === 0, '新 Run 首次失败不显示旧曲线');
  assert(await metrics.getByText('暂无训练指标数据', { exact: true }).count() === 0, '失败不误报无指标');
  assert(await metrics.getByText(/^更新于/).count() === 0, '新 Run 不沿用旧成功时间');
  await metrics.getByRole('switch').click();
  await mode({ metrics: 'success' });
  await refresh();
  await metrics.getByText('10', { exact: true }).waitFor();
  assert(await metrics.getByRole('alert').count() === 0, '重试成功清除错误');

  await mode({ metrics: 'empty' });
  await refresh();
  await metrics.getByText('暂无训练指标数据', { exact: true }).waitFor();
  assert(await metrics.getByRole('alert').count() === 0, '正常空记录不是错误');
  await mode({ metrics: 'held' });
  await page.getByRole('button', { name: '测试切换 A', exact: true }).click();
  await page.waitForFunction(() => window.__qa.held.length > 0);
  await mode({ metrics: 'success' });
  await page.getByRole('button', { name: '测试切换 B', exact: true }).click();
  await metrics.getByText('10', { exact: true }).waitFor();
  await page.evaluate(() => window.__qa.release());
  await page.waitForTimeout(100);
  assert(await metrics.getByText('10', { exact: true }).isVisible() && await metrics.getByText('1', { exact: true }).count() === 0, '迟到的 A 响应不覆盖 B');

  await mode({ metrics: 'held' });
  await page.waitForFunction(() => window.__qa.held.length > 0, undefined, { timeout: 6000 });
  const calls = await page.evaluate(() => window.__qa.calls.length);
  await page.waitForTimeout(4500);
  assert(await page.evaluate(() => window.__qa.calls.length) === calls, '慢请求期间自动轮询不叠加');
  await mode({ metrics: 'success' });
  await refresh();
  await page.evaluate(() => window.__qa.release());
  await metrics.getByRole('switch').click();
  assert(await metrics.getByText('10', { exact: true }).isVisible(), '手动刷新可替代慢请求');
  await metrics.getByRole('button', { name: '全选过程指标' }).click();
  assert(await metrics.locator('canvas').count() > 0, '全选过程指标保留曲线');

  await metrics.getByTitle('合并折线图', { exact: true }).click();
  await page.getByText('分指标折线图', { exact: true }).click();
  assert(await metrics.getByTitle('分指标折线图', { exact: true }).isVisible(), '切换分指标折线图');
  await metrics.getByTitle('分指标折线图', { exact: true }).click();
  await page.getByText('末值柱状图', { exact: true }).click();
  assert(await metrics.getByTitle('末值柱状图', { exact: true }).isVisible(), '切换末值柱状图');
  await metrics.getByTitle('末值柱状图', { exact: true }).click();
  await page.getByText('合并折线图', { exact: true }).click();
  await metrics.getByRole('combobox').nth(1).click();
  await page.keyboard.press('Escape');
  assert(await metrics.getByTitle('训练损失', { exact: true }).isVisible(), '过程指标选择器可打开并关闭');

  await mode({ code: 'partial' });
  await query();
  await codes.getByText(/2 个代码资产中有 1 个版本列表加载失败/).waitFor();
  assert(await codes.getByRole('cell', { name: '代码 A', exact: true }).isVisible(), '部分失败保留成功资产');
  assert(await codes.getByRole('cell', { name: '代码 B', exact: true }).count() === 0, '缺失资产不以完整结果展示');
  await page.screenshot({ path: 'output/playwright/code-partial.png', fullPage: true });
  await mode({ code: 'error' });
  await codes.getByRole('button', { name: '重试加载' }).click();
  await codes.getByText(/本次查询未成功/).waitFor();
  assert(await codes.getByRole('cell', { name: '代码 A', exact: true }).isVisible(), '整表失败保留上次表格并标记');
  await mode({ code: 'success' });
  await codes.getByRole('button', { name: '重试加载' }).click();
  await codes.getByRole('cell', { name: '代码 B', exact: true }).waitFor();
  assert(await codes.getByRole('alert').count() === 0, '代码重试恢复完整列表并消除告警');
  await codes.getByRole('textbox', { name: '代码名称 :' }).fill('代码 A');
  await query();
  await page.waitForFunction(() => !document.querySelector('#code-list').textContent.includes('代码 B'));
  assert(await codes.getByRole('cell', { name: '代码 A', exact: true }).isVisible(), '名称筛选仍可用');
  await codes.getByRole('button', { name: '重 置' }).click();
  await codes.getByRole('cell', { name: '代码 B', exact: true }).waitFor();
  assert(true, '重置查询恢复记录');
  await mode({ code: 'empty' });
  await query();
  await page.waitForFunction(() => !document.querySelector('#code-list').textContent.includes('代码 B'));
  assert(await codes.getByRole('alert').count() === 0, '代码正常空列表无错误告警');
  await mode({ metrics: 'success' });
  await page.getByRole('button', { name: '测试手动 Run ID', exact: true }).click();
  await metrics.getByPlaceholder('运行记录编号（高级）').fill('  run-b  ');
  await metrics.getByRole('button', { name: '加载指标' }).click();
  await metrics.getByText('10', { exact: true }).waitFor();
  assert(true, '手动 Run ID 去空格后加载对应指标');
  await metrics.getByRole('switch').click();
  return { passed: checked.length, checks: checked };
}
