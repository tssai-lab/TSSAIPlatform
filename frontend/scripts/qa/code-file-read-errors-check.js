// 本地只读故障注入；不执行草稿创建、发布或删除。
async (page) => {
  await page.goto('http://127.0.0.1:18893/?view=assets');
  const checks = [];
  const assert = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  const mode = value => page.evaluate(value => { window.__qa.assetMode = value; }, value);
  const manage = () => page.getByRole('row').filter({ has: page.getByRole('cell', { name: '测试资产 A', exact: true }) }).getByRole('button', { name: '管理', exact: true }).click();
  await manage();
  const text = '只读文件 README.md · v2-asset-a';
  await page.getByText(text, { exact: true }).waitFor();
  await mode('file-error');
  await page.getByRole('tree').getByText('train.py', { exact: true }).click();
  await page.getByRole('button', { name: '重试文件', exact: true }).waitFor();
  assert(await page.getByText(text, { exact: true }).count() === 0, '文件失败清除旧内容并显示持续错误');
  await mode('success');
  await page.getByRole('button', { name: '重试文件', exact: true }).click();
  await page.getByText('只读文件 train.py · v2-asset-a', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: '重试文件', exact: true }).count() === 0, '文件重试成功恢复内容并清除错误');
  await mode('file-held');
  await page.getByRole('tree').getByText('README.md', { exact: true }).click();
  await page.waitForFunction(() => window.__qa.held.length === 1);
  await mode('success');
  await page.getByRole('tree').getByText('train.py', { exact: true }).click();
  await page.getByText('只读文件 train.py · v2-asset-a', { exact: true }).waitFor();
  await page.evaluate(async () => { window.__qa.release(); await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); });
  assert(await page.getByText('只读文件 train.py · v2-asset-a', { exact: true }).count() === 1, '较早文件迟到后当前内容保持正确');
  await mode('tree-error');
  await page.getByRole('button', { name: '查看文件', exact: true }).first().click();
  await page.getByRole('button', { name: '重试目录', exact: true }).waitFor();
  assert(await page.getByText('目录读取失败', { exact: true }).count() === 1, '目录读取失败不显示正常空目录');
  await mode('success');
  await page.getByRole('button', { name: '重试目录', exact: true }).click();
  await page.getByText('只读文件 README.md · v1-asset-a', { exact: true }).waitFor();
  assert(true, '目录重试恢复当前版本而非误开其它版本');
  await mode('list-invalid');
  await page.getByRole('button', { name: 'back', exact: true }).click();
  await page.getByRole('button', { name: '重试列表', exact: true }).waitFor();
  assert(await page.getByText('资产列表未更新', { exact: true }).count() === 1, '错误响应保持列表失败提示');
  await mode('success');
  await page.getByRole('button', { name: '重试列表', exact: true }).click();
  await page.getByRole('cell', { name: '测试资产 A', exact: true }).waitFor();
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).some(button => button.textContent === '重试列表'));
  assert(true, '列表重试恢复后移除错误');
  const before = await page.evaluate(() => window.__qa.assetCalls.length);
  await page.getByRole('textbox', { name: '归属用户 :' }).fill('unknown-user');
  await page.getByRole('button', { name: '查 询', exact: true }).click();
  await page.getByText('未找到该用户，请检查用户名或输入用户 ID', { exact: true }).waitFor();
  assert(await page.evaluate(() => window.__qa.assetCalls.length) === before, '未知用户名查询不发送无归属筛选的请求');
  await page.getByRole('button', { name: '重 置', exact: true }).click();
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).some(button => button.textContent === '重试列表'));
  assert(await page.getByRole('cell', { name: '测试资产 A', exact: true }).count() === 1, '重置筛选仍恢复正常列表');
  assert(await page.evaluate(() => window.__qa.assetCalls.every(call => call.method === 'GET')), '全部验收请求均为 GET');
  return { passed: checks.length, checks };
}
