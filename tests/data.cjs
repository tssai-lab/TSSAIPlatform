const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('../frontend/node_modules/typescript');
const source = fs.readFileSync(`${__dirname}/../frontend/src/pages/manual-label/data.ts`, 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = { exports: {} };
new Function('exports', 'module', output)(mod.exports, mod);
const { parseCsv, validateProject } = mod.exports;
assert.deepEqual(parseCsv('\uFEFFtime,value\r\n"t,1",2\r\nt2,3'), { columns: ['time', 'value'], rows: [['t,1', '2'], ['t2', '3']] });
assert.throws(() => parseCsv('time,value\nt1,1,2'));
assert.throws(() => parseCsv('time,value\n"t1,2'));
assert.throws(() => parseCsv('time,value\nt1,abc'));
const project = { version: 1, items: [{ id: '1', name: 'test.csv', kind: 'series', ...parseCsv('time,value\n0,2\n1,3'), marks: [{ label: '异常', start: 0, end: 1 }], done: true }] };
assert.deepEqual(validateProject(JSON.parse(JSON.stringify(project))), project);
assert.throws(() => validateProject({ ...project, items: [{ ...project.items[0], marks: [{ label: '异常', start: 0, end: 4 }] }] }));
console.log('CSV 解析、错误输入、项目恢复与区间校验通过');
const { parseTep } = mod.exports;
// 使用合成数据验证 52 通道解析，不把真实数据集提交到仓库。
const row = Array.from({ length: 52 }, (_, i) => String(i + 1)).join(' ');
const parsed = parseTep(`${row}\n${row}`);
assert.equal(parsed.columns.length, 53);
assert.equal(parsed.rows.length, 2);
const transposed = parseTep(Array.from({ length: 52 }, () => Array(500).fill('1').join(' ')).join('\n'));
assert.equal(transposed.rows.length, 500);
assert.equal(transposed.columns.length, 53);
assert.throws(() => parseTep('1 2 3\n4 5 6'));
assert.throws(() => parseTep(Array(52).fill('NaN').join(' ')));
console.log('52 通道时序解析与转置验证通过');
const labeled = JSON.parse(JSON.stringify(project));
labeled.items[0].marks[0].details = { state: '异常', fault_type: 'IDV04', affected_channels: 'XMV_10;XMEAS_9', note: '流量抬升' };
assert.deepEqual(validateProject(JSON.parse(JSON.stringify(labeled))), labeled);
labeled.items[0].marks[0].details = { state: 123 };
assert.throws(() => validateProject(labeled));
console.log('结构化标签导出恢复与非法属性校验通过，旧项目兼容');
